// Regenerates the parts of the docs that come from the schemas: the README stats block and docs/fields.md.
// `node scripts/generate.ts` writes them; validate.ts fails when the committed files differ.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { BASE_URL, familyOrder, familyVersions, loadSchemas, Registry } from "../lib/schemas.ts";
import { buildModel, flatten, type FieldNode } from "../lib/tree.ts";
import { constraintWords } from "../lib/words.ts";

const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");
const show = (v: unknown) => (typeof v === "string" ? v : JSON.stringify(v));

function valuesText(n: FieldNode): string {
  const words = constraintWords(n);
  const each = n.array ? "list, each " : "";
  const parts = n.enum ? [`${each}one of: ${n.enum.map((v) => `\`${show(v)}\``).join(", ")}`]
    : n.format && words.some((w) => w.startsWith("a ")) ? [] : [n.label];
  parts.push(...words.map((w) => (n.array && w.startsWith("a ") ? `each ${w}` : w)));
  if (n.pattern) parts.push(`format \`${n.pattern}\``);
  return parts.join("; ");
}

function fieldsDoc(root: string): string {
  const files = loadSchemas(root), reg = new Registry(files), families = familyVersions(files);
  const out = [readFileSync(join(root, "docs/fields.intro.md"), "utf8").trimEnd(), ""];
  for (const family of familyOrder([...families.keys()]).filter((f) => f !== "common")) {
    const latest = families.get(family)!.at(-1)!;
    const m = buildModel(latest, reg);
    const page = `${BASE_URL}${family}/v${latest.version}/`;
    out.push(`## ${m.title ?? family}`, "", `Family \`${family}\`, version ${latest.version}. ${m.description ?? ""}`.trim(), "");
    out.push(`Schema: <${latest.expectedId}> · Explorer: <${page}>`, "");
    for (const section of m.sections) {
      const rows = flatten(section.root).filter((n) => n.path);
      if (!rows.length) continue;
      out.push(`### ${section.title}`, "");
      if (section.description) out.push(section.description, "");
      out.push("| Field | What it means | Values | Required |", "|---|---|---|---|");
      for (const n of rows) {
        const meaning = [n.description ?? n.title ?? "", ...n.rules, n.recordOf ? `Each entry is one ${n.recordOf} record (see above).` : ""].filter(Boolean).join(" ");
        out.push(`| [\`${n.path}\`](${page}#${n.anchor}) | ${cell(meaning || "—")} | ${cell(n.forbidden ? "not allowed" : valuesText(n))} | ${n.required ? "yes" : "no"} |`);
      }
      out.push("");
    }
  }
  return out.join("\n");
}

function statsBlock(root: string): string {
  const families = familyVersions(loadSchemas(root));
  const total = [...families.values()].reduce((n, v) => n + v.length, 0);
  const rows = familyOrder([...families.keys()]).map((family) => {
    const vs = families.get(family)!, latest = vs.at(-1)!;
    return `| \`${family}\` | [v${latest.version}](${latest.expectedId}) | ${vs.length} | [explore](${BASE_URL}${family}/latest/) |`;
  });
  return [
    "<!-- stats:start -->",
    "| Family | Latest version | Versions | Explorer |",
    "|---|---|---|---|",
    ...rows,
    "",
    `${families.size} schema families, ${total} version file${total === 1 ? "" : "s"}. This block is generated by \`node scripts/generate.ts\`; do not edit it by hand.`,
    "<!-- stats:end -->",
  ].join("\n");
}

/** [repo path, expected content] for every generated file. */
export function generated(root: string): [string, string][] {
  const readme = readFileSync(join(root, "README.md"), "utf8");
  const re = /<!-- stats:start -->[\s\S]*?<!-- stats:end -->/;
  if (!re.test(readme)) throw new Error("README.md has no <!-- stats:start --> … <!-- stats:end --> block");
  return [
    ["README.md", readme.replace(re, statsBlock(root))],
    ["docs/fields.md", fieldsDoc(root) + "\n"],
  ];
}

if (import.meta.main) {
  const root = join(import.meta.dirname, "..");
  for (const [path, content] of generated(root)) writeFileSync(join(root, path), content);
  console.log("Wrote README.md stats block and docs/fields.md");
}
